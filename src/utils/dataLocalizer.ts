// Localize Calendar Events
export function localizeCalendarEvents(events: CalendarActivityEvent[], lang: LanguageCode): CalendarActivityEvent[] {
  if (lang === 'en') return events;
  return events.map((e) => {
    const eventTranslation = EVENT_TRANSLATIONS[e.id];
    const contractTranslation = e.contractId ? CONTRACT_TRANSLATIONS[e.contractId] : undefined;

    const title = eventTranslation?.title?.[lang] || localizeText(e.title, lang);
    const description = eventTranslation?.description?.[lang] || e.description;
    const contractName = (contractTranslation?.name?.[lang]) || localizeText(e.contractName, lang);
    const partyName = e.partyName ? LOCALIZED_COMPANIES[e.partyName]?.[lang] || e.partyName : e.partyName;
    const ownerName = e.ownerName ? LOCALIZED_PEOPLE[e.ownerName]?.[lang] || e.ownerName : e.ownerName;
    const category = localizeText(e.category, lang);
    const status = e.status ? LOCALIZED_STATUSES[e.status]?.[lang] || e.status : e.status;
    const reminderStatus = localizeText(e.reminderStatus, lang);

    return {
      ...e,
      title,
      description,
      contractName,
      partyName,
      ownerName,
      category,
      status,
      reminderStatus,
    };
  });
}

